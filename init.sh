#!/bin/sh
# A POSIX-shell bootstrapper. Generated projects do not depend on its runtime.

set -eu

KIT_VERSION="0.3.0"
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROFILE_DIR="$SCRIPT_DIR/profiles"
TEMPLATE_DIR="$SCRIPT_DIR/templates"
CORE_DIR="$SCRIPT_DIR/core"

die() {
    printf '%s\n' "error: $*" >&2
    exit 2
}

usage() {
    cat <<'USAGE'
Usage:
  sh init.sh list-profiles
  sh init.sh init TARGET [options]

Options:
  --name NAME                    Project name (defaults to TARGET's basename)
  --description TEXT              One-line project purpose
  --profile PROFILE               Base profile
  --set SECTION.KEY=VALUE         Override one profile value
  --tdd | --no-tdd                Enable or disable test-first development
  --adr | --no-adr                Create or omit the ADR template
  --claude-compat                 Also create a CLAUDE.md pointer
  --force                         Allow a non-empty target and replace managed files
  --dry-run                       List files without writing them
USAGE
}

# Profiles use only a small TOML subset: top-level fields, [section] tables,
# quoted strings, and booleans. This keeps the bootstrap dependency-free.
profile_value() {
    awk -v wanted_section="$2" -v wanted_key="$3" '
        function trim(value) { sub(/^[[:space:]]+/, "", value); sub(/[[:space:]]+$/, "", value); return value }
        /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
        /^[[:space:]]*\[/ {
            section = $0
            sub(/^[[:space:]]*\[/, "", section)
            sub(/\][[:space:]]*$/, "", section)
            next
        }
        section == wanted_section {
            expression = "^[[:space:]]*" wanted_key "[[:space:]]*="
            if ($0 ~ expression) {
                value = $0
                sub(expression, "", value)
                value = trim(value)
                sub(/^"/, "", value)
                sub(/"$/, "", value)
                print value
                exit
            }
        }
    ' "$1"
}

list_profiles() {
    for profile_file in "$PROFILE_DIR"/*.toml; do
        [ -f "$profile_file" ] || continue
        profile_id=$(basename "$profile_file" .toml)
        description=$(profile_value "$profile_file" "" description)
        printf '%-16s %s\n' "$profile_id" "$description"
    done
}

toml_escape() {
    printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

sed_escape() {
    printf '%s' "$1" | sed 's/[\\&|]/\\&/g'
}

boolean_label() {
    case "$1" in
        true) printf '%s' "예" ;;
        false) printf '%s' "아니오" ;;
        *) printf '%s' "$1" ;;
    esac
}

assert_boolean() {
    case "$2" in
        true|false) ;;
        *) die "$1 must be true or false" ;;
    esac
}

render_template() {
    sed \
        -e "s|{{PROJECT_NAME}}|$(sed_escape "$PROJECT_NAME")|g" \
        -e "s|{{PROJECT_DESCRIPTION}}|$(sed_escape "$PROJECT_DESCRIPTION")|g" \
        -e "s|{{PROFILE_ID}}|$(sed_escape "$PROFILE_ID")|g" \
        -e "s|{{PROFILE_NAME}}|$(sed_escape "$PROFILE_NAME")|g" \
        -e "s|{{STACK_LANGUAGE}}|$(sed_escape "$STACK_LANGUAGE")|g" \
        -e "s|{{STACK_FRAMEWORK}}|$(sed_escape "$STACK_FRAMEWORK")|g" \
        -e "s|{{STACK_DATABASE}}|$(sed_escape "$STACK_DATABASE")|g" \
        -e "s|{{DEVELOPMENT_TDD}}|$(sed_escape "$(boolean_label "$DEVELOPMENT_TDD")")|g" \
        -e "s|{{DEVELOPMENT_COMMIT_STYLE}}|$(sed_escape "$DEVELOPMENT_COMMIT_STYLE")|g" \
        -e "s|{{DEVELOPMENT_TESTING}}|$(sed_escape "$DEVELOPMENT_TESTING")|g" \
        -e "s|{{ARCHITECTURE_STYLE}}|$(sed_escape "$ARCHITECTURE_STYLE")|g" \
        -e "s|{{ARCHITECTURE_API}}|$(sed_escape "$ARCHITECTURE_API")|g" \
        -e "s|{{KIT_VERSION}}|$KIT_VERSION|g" \
        "$1"
}

record_file() {
    relative_path=$1
    if [ -e "$TARGET/$relative_path" ]; then
        action=replace
    else
        action=create
    fi
    if [ "$DRY_RUN" = true ]; then
        printf '  %-7s %s\n' "$action" "$relative_path"
    fi
}

write_template() {
    source_path=$1
    relative_path=$2
    record_file "$relative_path"
    [ "$DRY_RUN" = true ] && return
    mkdir -p "$(dirname "$TARGET/$relative_path")"
    render_template "$source_path" > "$TARGET/$relative_path"
}

copy_core_file() {
    source_path=$1
    relative_path=$2
    record_file "$relative_path"
    [ "$DRY_RUN" = true ] && return
    mkdir -p "$(dirname "$TARGET/$relative_path")"
    cp "$source_path" "$TARGET/$relative_path"
}

write_harness_toml() {
    record_file "harness.toml"
    [ "$DRY_RUN" = true ] && return
    {
        printf '%s\n\n' "# Generated by harness-kit. Project-specific adjustments belong here."
        printf '[kit]\nversion = "%s"\n\n' "$KIT_VERSION"
        printf '[project]\nname = "%s"\ndescription = "%s"\n\n' "$(toml_escape "$PROJECT_NAME")" "$(toml_escape "$PROJECT_DESCRIPTION")"
        printf '[profile]\nid = "%s"\nname = "%s"\n\n' "$(toml_escape "$PROFILE_ID")" "$(toml_escape "$PROFILE_NAME")"
        printf '[stack]\nlanguage = "%s"\nframework = "%s"\ndatabase = "%s"\n\n' "$(toml_escape "$STACK_LANGUAGE")" "$(toml_escape "$STACK_FRAMEWORK")" "$(toml_escape "$STACK_DATABASE")"
        printf '[development]\ntdd = %s\ncommit_style = "%s"\ntesting = "%s"\n\n' "$DEVELOPMENT_TDD" "$(toml_escape "$DEVELOPMENT_COMMIT_STYLE")" "$(toml_escape "$DEVELOPMENT_TESTING")"
        printf '[architecture]\nstyle = "%s"\napi = "%s"\n\n' "$(toml_escape "$ARCHITECTURE_STYLE")" "$(toml_escape "$ARCHITECTURE_API")"
        printf '[docs]\nintent = %s\nprd = %s\narchitecture = %s\nadr = %s\n' "$DOCS_INTENT" "$DOCS_PRD" "$DOCS_ARCHITECTURE" "$DOCS_ADR"
    } > "$TARGET/harness.toml"
}

apply_override() {
    override_key=${1%%=*}
    override_value=${1#*=}
    [ "$override_key" != "$1" ] || die "--set must use section.key=value"
    case "$override_key" in
        stack.language) STACK_LANGUAGE=$override_value ;;
        stack.framework) STACK_FRAMEWORK=$override_value ;;
        stack.database) STACK_DATABASE=$override_value ;;
        development.tdd) DEVELOPMENT_TDD=$override_value ;;
        development.commit_style) DEVELOPMENT_COMMIT_STYLE=$override_value ;;
        development.testing) DEVELOPMENT_TESTING=$override_value ;;
        architecture.style) ARCHITECTURE_STYLE=$override_value ;;
        architecture.api) ARCHITECTURE_API=$override_value ;;
        docs.intent) DOCS_INTENT=$override_value ;;
        docs.prd) DOCS_PRD=$override_value ;;
        docs.architecture) DOCS_ARCHITECTURE=$override_value ;;
        docs.adr) DOCS_ADR=$override_value ;;
        *) die "unsupported override: $override_key" ;;
    esac
}

init_project() {
    [ "$#" -ge 1 ] || die "init requires a target directory"
    TARGET=$1
    shift
    PROJECT_NAME=$(basename "$TARGET")
    PROJECT_DESCRIPTION="TODO: describe the project in docs/INTENT.md"
    PROFILE_ID=""
    FORCE=false
    DRY_RUN=false
    CLAUDE_COMPAT=false
    TDD_OVERRIDE=""
    ADR_OVERRIDE=""
    overrides_file=$(mktemp "${TMPDIR:-/tmp}/harness-kit.XXXXXX")
    trap 'rm -f "$overrides_file"' EXIT HUP INT TERM

    while [ "$#" -gt 0 ]; do
        case "$1" in
            --name) [ "$#" -ge 2 ] || die "--name requires a value"; PROJECT_NAME=$2; shift 2 ;;
            --description) [ "$#" -ge 2 ] || die "--description requires a value"; PROJECT_DESCRIPTION=$2; shift 2 ;;
            --profile) [ "$#" -ge 2 ] || die "--profile requires a value"; PROFILE_ID=$2; shift 2 ;;
            --set) [ "$#" -ge 2 ] || die "--set requires a value"; printf '%s\n' "$2" >> "$overrides_file"; shift 2 ;;
            --tdd) TDD_OVERRIDE=true; shift ;;
            --no-tdd) TDD_OVERRIDE=false; shift ;;
            --adr) ADR_OVERRIDE=true; shift ;;
            --no-adr) ADR_OVERRIDE=false; shift ;;
            --claude-compat) CLAUDE_COMPAT=true; shift ;;
            --force) FORCE=true; shift ;;
            --dry-run) DRY_RUN=true; shift ;;
            --help|-h) usage; exit 0 ;;
            *) die "unknown option: $1" ;;
        esac
    done

    [ -n "$PROFILE_ID" ] || die "--profile is required; run 'sh init.sh list-profiles'"
    PROFILE_FILE="$PROFILE_DIR/$PROFILE_ID.toml"
    [ -f "$PROFILE_FILE" ] || die "unknown profile '$PROFILE_ID'; run 'sh init.sh list-profiles'"

    if [ -d "$TARGET" ] && [ "$(cd "$TARGET" && pwd)" = "$SCRIPT_DIR" ]; then
        die "refusing to generate into the harness-kit source directory"
    fi
    if [ -e "$TARGET" ] && [ ! -d "$TARGET" ]; then
        die "target exists but is not a directory: $TARGET"
    fi
    if [ -d "$TARGET" ] && [ -n "$(find "$TARGET" -mindepth 1 -maxdepth 1 -print -quit)" ] && [ "$FORCE" != true ]; then
        die "target is not empty: $TARGET. Use --force only after reviewing managed files."
    fi

    PROFILE_NAME=$(profile_value "$PROFILE_FILE" "" name)
    STACK_LANGUAGE=$(profile_value "$PROFILE_FILE" stack language)
    STACK_FRAMEWORK=$(profile_value "$PROFILE_FILE" stack framework)
    STACK_DATABASE=$(profile_value "$PROFILE_FILE" stack database)
    DEVELOPMENT_TDD=$(profile_value "$PROFILE_FILE" development tdd)
    DEVELOPMENT_COMMIT_STYLE=$(profile_value "$PROFILE_FILE" development commit_style)
    DEVELOPMENT_TESTING=$(profile_value "$PROFILE_FILE" development testing)
    ARCHITECTURE_STYLE=$(profile_value "$PROFILE_FILE" architecture style)
    ARCHITECTURE_API=$(profile_value "$PROFILE_FILE" architecture api)
    DOCS_INTENT=$(profile_value "$PROFILE_FILE" docs intent)
    DOCS_PRD=$(profile_value "$PROFILE_FILE" docs prd)
    DOCS_ARCHITECTURE=$(profile_value "$PROFILE_FILE" docs architecture)
    DOCS_ADR=$(profile_value "$PROFILE_FILE" docs adr)

    [ -n "$TDD_OVERRIDE" ] && DEVELOPMENT_TDD=$TDD_OVERRIDE
    [ -n "$ADR_OVERRIDE" ] && DOCS_ADR=$ADR_OVERRIDE
    while IFS= read -r override || [ -n "$override" ]; do
        [ -n "$override" ] && apply_override "$override"
    done < "$overrides_file"

    assert_boolean development.tdd "$DEVELOPMENT_TDD"
    assert_boolean docs.intent "$DOCS_INTENT"
    assert_boolean docs.prd "$DOCS_PRD"
    assert_boolean docs.architecture "$DOCS_ARCHITECTURE"
    assert_boolean docs.adr "$DOCS_ADR"

    if [ "$DRY_RUN" = true ]; then
        printf '%s\n' "Would generate harness in: $TARGET"
    else
        mkdir -p "$TARGET"
    fi

    write_harness_toml
    write_template "$TEMPLATE_DIR/AGENTS.md.tmpl" "AGENTS.md"
    write_template "$TEMPLATE_DIR/docs/INTENT.md.tmpl" "docs/INTENT.md"
    write_template "$TEMPLATE_DIR/docs/LLM_WIKI.md.tmpl" "docs/LLM_WIKI.md"
    write_template "$TEMPLATE_DIR/docs/PRD.md.tmpl" "docs/PRD.md"
    write_template "$TEMPLATE_DIR/phases/README.md.tmpl" "phases/README.md"
    write_template "$TEMPLATE_DIR/.harness/README.md.tmpl" ".harness/README.md"
    copy_core_file "$CORE_DIR/workflows/IMPLEMENTATION.md" ".harness/IMPLEMENTATION.md"
    copy_core_file "$CORE_DIR/scripts/verify-harness.sh" "scripts/verify-harness.sh"
    copy_core_file "$CORE_DIR/scripts/harness.sh" "scripts/harness.sh"
    copy_core_file "$CORE_DIR/templates/phase.md.tmpl" ".harness/templates/phase.md.tmpl"
    copy_core_file "$CORE_DIR/templates/step.md.tmpl" ".harness/templates/step.md.tmpl"
    copy_core_file "$CORE_DIR/templates/step-evidence.md.tmpl" ".harness/templates/step-evidence.md.tmpl"
    if [ "$DOCS_ARCHITECTURE" = true ]; then
        write_template "$TEMPLATE_DIR/docs/ARCHITECTURE.md.tmpl" "docs/ARCHITECTURE.md"
    fi
    if [ "$DOCS_ADR" = true ]; then
        write_template "$TEMPLATE_DIR/docs/ADR/0000-template.md.tmpl" "docs/ADR/0000-template.md"
    fi
    if [ "$CLAUDE_COMPAT" = true ]; then
        write_template "$TEMPLATE_DIR/CLAUDE.md.tmpl" "CLAUDE.md"
    fi

    if [ "$DRY_RUN" = false ]; then
        printf '%s\n' "Created harness for '$PROJECT_NAME' in $TARGET"
        printf '%s\n' "Next: fill docs/INTENT.md, review harness.toml, then run:"
        printf '  sh %s/scripts/verify-harness.sh %s\n' "$TARGET" "$TARGET"
    fi
}

case "${1:-}" in
    list-profiles) shift; [ "$#" -eq 0 ] || die "list-profiles accepts no options"; list_profiles ;;
    init) shift; init_project "$@" ;;
    --help|-h|"") usage ;;
    *) die "unknown command: $1" ;;
esac
